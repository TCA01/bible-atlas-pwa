const CACHE_NAME = 'logos-atlas-v1';
const STATIC_ASSETS = [
  '/en',
  '/manifest.json',
  '/icon.svg',
  '/api/geo/places',
  '/api/geo/journeys',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(STATIC_ASSETS)).catch(() => {})
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  // Never permanently cache copyrighted Bible API versions (NIV, ESV, NRSV)
  if (url.pathname.startsWith('/api/bible/NIV') ||
      url.pathname.startsWith('/api/bible/ESV') ||
      url.pathname.startsWith('/api/bible/NRSV')) {
    return;
  }

  if (url.origin === self.location.origin) {
    event.respondWith(
      caches.match(request).then((cached) => {
        const networkFetch = fetch(request)
          .then((res) => {
            if (res && res.status === 200) {
              const copy = res.clone();
              caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
            }
            return res;
          })
          .catch(() => cached);
        return cached || networkFetch;
      })
    );
  }
});
